package flats.common.protocol;

/**
 * Результат выполнения команды на сервере.
 */
public enum Status {
    /** Команда выполнена. */
    OK,
    /** Команда не выполнена из-за ошибки в запросе или состояния данных. */
    ERROR,
    /** Не указаны или неверны логин и пароль. */
    AUTH_REQUIRED,
    /** Элемент принадлежит другому пользователю. */
    FORBIDDEN,
    /** Элемент не найден. */
    NOT_FOUND
}
